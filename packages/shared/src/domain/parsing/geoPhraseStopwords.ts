/**
 * Топонимы-омонимы служебных/нарицательных слов: не матчить по phrase без regionScope.
 *
 * ⚠️ СКОУП: список влияет ТОЛЬКО на извлечение топонимов (geo phrase-фаза),
 * НЕ удаляет слова из текста для классификации типа события и прочих процессоров.
 * Потребители — строго гео: `placeScanIndex.resolvePhraseCandidates`
 * и `channelCityListPromo.isGarbageIngestPlaceName` (валидация имени place на write-path).
 *
 * Примеры ловушек:
 * - «Старый Оскол или район» → не locality «Или» (RU-IRK);
 * - «Не попадите под осколки» → не д. Осколки (RU-KIR).
 */
export const GEO_PHRASE_STOPWORDS = new Set([
  // Служебные слова / союзы (омонимы НП).
  "или",
  "наша",
  "наш",
  "меры",
  "мера",
  "это",
  "все",
  "вся",
  "они",
  "она",
  "оно",
  // Нарицательные-ловушки домена сообщений ПВО (статус/последствие, не НП):
  "осколки", // «осколки сбитых БПЛА» → совпало с д. Осколки (RU-KIR)
  "осколок", // ед. число той же ловушки
  "тревога", // «воздушная тревога» — статус события
  "опасность", // «опасность атаки БПЛА» — статус события
  "отбой", // «отбой тревоги» — статус события
  "угроза", // «угроза атаки» — статус события
]);

export function isGeoPhraseStopword(phraseLower: string): boolean {
  return GEO_PHRASE_STOPWORDS.has(phraseLower);
}
